render() {
  local name="$1" glyph="$2" color="$3" themeDir="$4"
  local svg='<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24">'
  IFS='|' read -ra paths <<< "$glyph"
  for p in "${paths[@]}"; do
    svg+="<path d=\"$p\" fill=\"$color\"/>"
  done
  svg+='</svg>'
  for dens in "mdpi 24" "hdpi 36" "xhdpi 48" "xxhdpi 72" "xxxhdpi 96"; do
    local bucket="${dens%% *}" size="${dens##* }"
    local dir="$RES/drawable-${themeDir}${bucket}"
    mkdir -p "$dir"
    printf '%s' "$svg" | rsvg-convert -w "$size" -h "$size" -o "$dir/$name.png" /dev/stdin
  done
}

